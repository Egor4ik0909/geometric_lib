# Вычисляет площадь квадрата.
#
#   Параметр на вход:
#       a - длина стороны квадрата
#
#   Пример вызова:
#       area(5)
#
#   Результат:
#       25
def area(a):
    return a * a


# Вычисляет периметр квадрата.
#
#   Параметр на вход:
#       a - длина стороны квадрата
#
#   Пример вызова:
#       perimeter(5)
#
#   Результат:
#       20
def perimeter(a):
    return 4 * a