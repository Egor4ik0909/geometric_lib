import math

# Вычисляет площадь круга.
#
# Параметр на вход:
# r - радиус круга
#
# Пример вызова:
# area(5)
#
# Результат:
# 78.53981633974483
def area(r):
    return math.pi * r * r

# Вычисляет периметр круга.
#
# Параметр на вход:
# r - радиус круга
#
# Пример вызова:
# perimeter(5)
#
# Результат:
# 31.41592653589793
def perimeter(r):
    return 2 * math.pi * r